// Writes src/assets.generated.ts: edu's Typst files, its CSS, the prompt catalogue and the
// prompt examples as constants, so the package works in browsers and workers without fetching
// or bundler loaders. typst/, css/ and examples/ are the sources; a test checks the generated
// module is current.
//
// The catalogue comes from the `///` doc comments above each public function (the names lib.typ
// imports), so the prompt never drifts from the package: the description, the parameters, and
// an `example` code block.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path) => readFileSync(`${root}${path}`, "utf8");

/** Every Typst source and typst.toml, by file name. */
export const files = () =>
  Object.fromEntries(
    readdirSync(`${root}typst`)
      .filter((name) => /\.(typ|toml)$/.test(name))
      .sort()
      .map((name) => [name, read(`typst/${name}`)]),
  );

/** Public names, in lib.typ's order: what its `#import "x.typ": a, b` lines bring in. */
export const publicNames = (lib) =>
  [...lib.matchAll(/^#import "([^"]+)": (.+)$/gm)].map(([, file, names]) => ({
    file,
    names: names.split(",").map((n) => n.trim()),
  }));

/** The parameter list of the `#let name(` at `start`, up to its closing parenthesis. */
const params = (source, start) => {
  let depth = 0;
  for (let i = start; i < source.length; i++) {
    const c = source[i];
    if (c === "(") depth++;
    else if (c === ")" && --depth === 0) return source.slice(start + 1, i);
    else if (c === '"') i = source.indexOf('"', i + 1);
  }
  throw new Error("unclosed parameter list");
};

/** One FunctionDoc per public function, from the doc comment above its `#let`. */
export const catalogue = (sources) => {
  const docs = [];
  for (const { file, names } of publicNames(sources["lib.typ"])) {
    const source = sources[file];
    for (const name of names) {
      const at = source.search(new RegExp(`^#let ${name}\\(`, "m"));
      if (at < 0) throw new Error(`${file}: no #let ${name}(`);
      const lines = source.slice(0, at).split("\n");
      lines.pop();
      const doc = [];
      while (lines.length && lines.at(-1).startsWith("///")) doc.unshift(lines.pop().replace(/^\/\/\/ ?/, ""));
      if (!doc.length) throw new Error(`${file}: ${name} has no doc comment`);
      const text = doc.join("\n");
      const fence = /```example\n([\s\S]*?)\n```/.exec(text);
      const signature = `${name}(${params(source, at + `#let ${name}`.length)
        .split("\n")
        .map((l) => l.trim())
        .filter(Boolean)
        .join(" ")
        .replace(/,\s*$/, "")
        .replace(/\(\s+/g, "(")
        .replace(/\s+\)/g, ")")})`;
      docs.push({
        name,
        signature,
        description: text.replace(/```example\n[\s\S]*?\n```/, "").trim(),
        ...(fence ? { example: fence[1] } : {}),
      });
    }
  }
  return docs;
};

/** Prompt examples: examples/*.typ, whose first line is `// request: <what the user asked>`. */
export const examples = () =>
  readdirSync(`${root}examples`)
    .filter((name) => name.endsWith(".typ"))
    .sort()
    .map((name) => {
      const source = read(`examples/${name}`);
      const request = /^\/\/ request: (.*)\n/.exec(source);
      if (!request) throw new Error(`examples/${name}: first line must be "// request: …"`);
      return { title: name.replace(/\.typ$/, ""), request: request[1], output: source.slice(request[0].length) };
    });

// Non-ASCII as \u escapes: Arabic and Bengali text holds combining marks, which should stay
// out of .ts files (CLAUDE.md, Gotchas).
const literal = (value) =>
  JSON.stringify(value, null, 2).replace(
    /[\u007f-\uffff]/g,
    (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`,
  );

export const generate = () => {
  const sources = files();
  return [
    "// Generated by scripts/embed.mjs from typst/, css/edu.css and examples/. Don't edit.",
    "",
    `export const FILES: Record<string, string> = ${literal(sources)};`,
    "",
    `export const CSS_SOURCE = ${literal(read("css/edu.css"))};`,
    "",
    `export const CATALOGUE = ${literal(catalogue(sources))};`,
    "",
    `export const EXAMPLES = ${literal(examples())};`,
    "",
  ].join("\n");
};

if (import.meta.url === `file://${process.argv[1]}`) {
  // Only when it changed: the build runs this while turbo may be type-checking the package, which
  // reads the file (a rewrite truncates it first, and tsc then saw an empty file, "not a module").
  const out = `${root}src/assets.generated.ts`;
  const text = generate();
  if (readFileSync(out, "utf8") !== text) writeFileSync(out, text);
}
