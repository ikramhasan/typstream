// Writes src/assets.generated.ts: the Typst package's files and the prompt examples as constants,
// so the plugin works in browsers and workers without fetching or bundler loaders. typst/ and
// examples/ are the sources; a test checks the generated module is current.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (path) => readFileSync(`${root}${path}`, "utf8");

/** Every Typst source and typst.toml, by file name. */
export const files = () =>
  Object.fromEntries(
    readdirSync(`${root}typst`)
      .filter((name) => /\.(typ|toml)$/.test(name))
      .sort()
      .map((name) => [name, read(`typst/${name}`)]),
  );

/** Prompt examples: examples/*.typ, whose first line is `// request: <what the user asked>`. */
export const examples = () =>
  readdirSync(`${root}examples`)
    .filter((name) => name.endsWith(".typ"))
    .sort()
    .map((name) => {
      const source = read(`examples/${name}`);
      const request = /^\/\/ request: (.*)\n/.exec(source);
      if (!request) throw new Error(`examples/${name}: first line must be "// request: …"`);
      return { title: name.replace(/\.typ$/, ""), request: request[1], output: source.slice(request[0].length) };
    });

// Non-ASCII as \u escapes, which keeps invisible characters out of .ts files (CLAUDE.md, Gotchas).
const literal = (value) =>
  JSON.stringify(value, null, 2).replace(
    /[\u007f-\uffff]/g,
    (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`,
  );

export const generate = () =>
  [
    "// Generated by scripts/embed.mjs from typst/ and examples/. Don't edit.",
    "",
    `export const FILES: Record<string, string> = ${literal(files())};`,
    "",
    `export const EXAMPLES = ${literal(examples())};`,
    "",
  ].join("\n");

if (import.meta.url === `file://${process.argv[1]}`) writeFileSync(`${root}src/assets.generated.ts`, generate());
