// Writes src/widths.generated.ts: the advance widths of Libertinus Serif (regular, bold, italic,
// bold italic), the face Typst sets a diagram's labels in, so pele sizes boxes for the text Typst
// draws. Read from typst-assets 0.15.1 (the crate engine-wasm bundles fonts from): its cmap
// (format 4 or 12) and hmtx tables, in thousandths of an em, for the Basic Multilingual Plane.
//
//   node scripts/widths.mjs [<typst-assets fonts dir>]
//
// Without an argument it looks for the crate in Cargo's registry (`cargo fetch` in
// packages/engine-wasm puts it there).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

const findAssets = () => {
  const registry = join(process.env.CARGO_HOME ?? join(homedir(), ".cargo"), "registry", "src");
  for (const index of readdirSync(registry)) {
    const dir = join(registry, index, "typst-assets-0.15.1", "files", "fonts");
    try {
      readdirSync(dir);
      return dir;
    } catch {}
  }
  throw new Error(
    "typst-assets 0.15.1 isn't in Cargo's registry: run `cargo fetch` in packages/engine-wasm, or pass its fonts dir",
  );
};

/** Advance widths by code point, in font units, and the units per em. */
const advances = (path) => {
  const b = readFileSync(path);
  const v = new DataView(b.buffer, b.byteOffset, b.byteLength);
  const tables = {};
  for (let i = 0; i < v.getUint16(4); i++)
    tables[b.toString("latin1", 12 + i * 16, 16 + i * 16)] = v.getUint32(20 + i * 16);
  const upm = v.getUint16(tables.head + 18);
  const metrics = v.getUint16(tables.hhea + 34);
  const advance = (glyph) => v.getUint16(tables.hmtx + 4 * Math.min(glyph, metrics - 1));
  const cmap = tables.cmap;
  let table = null;
  for (let i = 0; i < v.getUint16(cmap + 2); i++) {
    const [platform, encoding, offset] = [
      v.getUint16(cmap + 4 + i * 8),
      v.getUint16(cmap + 6 + i * 8),
      v.getUint32(cmap + 8 + i * 8),
    ];
    const format = v.getUint16(cmap + offset);
    if (platform === 3 && encoding === 10 && format === 12) table = { format, at: cmap + offset };
    else if (platform === 3 && encoding === 1 && format === 4 && !table) table = { format, at: cmap + offset };
  }
  const widths = new Map();
  const { at } = table;
  if (table.format === 12) {
    for (let i = 0; i < v.getUint32(at + 12); i++) {
      const [start, end, glyph] = [
        v.getUint32(at + 16 + i * 12),
        v.getUint32(at + 20 + i * 12),
        v.getUint32(at + 24 + i * 12),
      ];
      for (let c = start; c <= end; c++) widths.set(c, advance(glyph + c - start));
    }
  } else {
    const segments = v.getUint16(at + 6) / 2;
    const ends = at + 14;
    const starts = ends + segments * 2 + 2;
    const deltas = starts + segments * 2;
    const offsets = deltas + segments * 2;
    for (let i = 0; i < segments; i++) {
      const [end, start, delta, offset] = [
        v.getUint16(ends + 2 * i),
        v.getUint16(starts + 2 * i),
        v.getInt16(deltas + 2 * i),
        v.getUint16(offsets + 2 * i),
      ];
      for (let c = start; c <= end && c !== 0xffff; c++) {
        let glyph = offset === 0 ? (c + delta) & 0xffff : v.getUint16(offsets + 2 * i + offset + 2 * (c - start));
        if (offset !== 0 && glyph) glyph = (glyph + delta) & 0xffff;
        if (glyph) widths.set(c, advance(glyph));
      }
    }
  }
  return { upm, widths };
};

/** Runs of consecutive code points: `[first, [width, …]]`, widths in thousandths of an em. */
const runs = ({ upm, widths }) => {
  const out = [];
  for (const c of [...widths.keys()].filter((c) => c >= 0x20 && c <= 0xffff).sort((a, b) => a - b)) {
    const w = Math.round((widths.get(c) * 1000) / upm);
    const last = out.at(-1);
    if (last && last[0] + last[1].length === c) last[1].push(w);
    else out.push([c, [w]]);
  }
  return out;
};

const dir = process.argv[2] ?? findAssets();
const faces = ["Regular", "Bold", "Italic", "BoldItalic"].map((style) =>
  runs(advances(join(dir, `LibertinusSerif-${style}.otf`))),
);
writeFileSync(
  `${root}src/widths.generated.ts`,
  `// Generated by scripts/widths.mjs from typst-assets 0.15.1's Libertinus Serif. Do not edit.
// Per face (regular, bold, italic, bold italic): runs of consecutive code points, [first, widths],
// widths in thousandths of an em.
export const WIDTHS: readonly (readonly [number, readonly number[]])[][] = ${JSON.stringify(faces)};
`,
);
console.log(
  `src/widths.generated.ts: ${faces.map((f) => f.reduce((n, [, w]) => n + w.length, 0)).join(", ")} code points`,
);
