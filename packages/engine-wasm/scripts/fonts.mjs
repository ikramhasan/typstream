// Writes dist/fonts.js and dist/fonts.d.ts (build.sh runs it once the wasm and dist/fonts/ exist):
// the base fonts' URLs, and the lazy font registries: each file's URL with the FontInfo Typst
// computes for its faces (`Engine.font_info`), so engines register them without downloading them
// (PLAN §6.4, #11). `extraFonts` are the rest of Typst's bundled faces (#128), `scriptFonts` the
// fonts for scripts the bundled ones don't cover. Run with the font file names:
//   node scripts/fonts.mjs --base A.ttf B.ttf --extra C.ttf --script Arab:NotoNaskhArabic-Regular.ttf …
//
// The same `Engine.font_info` makes registry entries for other fonts (an app's CJK font, say):
//   node scripts/fonts.mjs --info path/to/font.ttf
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dist = fileURLToPath(new URL("../dist/", import.meta.url));
const { Engine, initSync } = await import(new URL("../dist/engine.js", import.meta.url).href);
initSync({ module: readFileSync(`${dist}engine_bg.wasm`) });

const args = process.argv.slice(2);

if (args[0] === "--info") {
  for (const path of args.slice(1)) console.log(Engine.font_info(readFileSync(path)));
  process.exit(0);
}

const base = [];
const extra = [];
const script = [];
let list = null;
for (const arg of args) {
  if (arg === "--base") list = base;
  else if (arg === "--extra") list = extra;
  else if (arg === "--script") list = script;
  else if (list) list.push(arg);
  else throw new Error(`fonts.mjs: unexpected argument ${arg}`);
}

const url = (file) => `new URL(${JSON.stringify(`./fonts/${file}`)}, import.meta.url)`;

/** A lazy font's entry: its file, family and FontInfo. */
const lazy = (file) => {
  const info = Engine.font_info(readFileSync(`${dist}fonts/${file}`));
  const faces = JSON.parse(info);
  if (faces.length === 0) throw new Error(`fonts.mjs: ${file} has no faces`);
  return { file, family: faces[0].family, info };
};
const extras = extra.map(lazy);
const scripts = script.map((spec) => {
  const [codes, file] = spec.split(":");
  return { ...lazy(file), scripts: codes.split(",") };
});

const entry = (e) =>
  `  { url: ${url(e.file)}, file: ${JSON.stringify(e.file)}, family: ${JSON.stringify(e.family)}, ` +
  `${e.scripts ? `scripts: ${JSON.stringify(e.scripts)}, ` : ""}info: ${JSON.stringify(e.info)} },`;

const js = [
  "// Generated by scripts/fonts.mjs: the fonts in ./fonts (licenses in ./fonts/NOTICE and ./fonts/LICENSE-Noto.txt).",
  "export const baseFonts = [",
  ...base.map((file) => `  ${url(file)},`),
  "];",
  "export const extraFonts = [",
  ...extras.map(entry),
  "];",
  "export const scriptFonts = [",
  ...scripts.map(entry),
  "];",
  "",
].join("\n");
writeFileSync(`${dist}fonts.js`, js);

const families = (entries) => [...new Set(entries.map((e) => e.family))].join(", ");
writeFileSync(
  `${dist}fonts.d.ts`,
  `/**
 * URLs of the base font set, which engines load at startup: Libertinus Serif (regular, bold,
 * italic), New Computer Modern Math (Book, the face Typst sets math in) and DejaVu Sans Mono.
 */
export declare const baseFonts: URL[];
/**
 * A font file registered by its metadata and downloaded the first time a document uses it.
 * \`info\` is what \`Engine.font_info\` returns for the file (Typst's FontInfo per face, as JSON):
 * pass it to \`Engine.register_font\`, then the bytes from \`url\` to \`Engine.load_font\`.
 */
export interface LazyFont {
  url: URL;
  /** The file's name in \`dist/fonts/\`, e.g. to serve the fonts from another origin. */
  file: string;
  family: string;
  info: string;
}
/** A lazy font for scripts the bundled fonts don't cover. */
export interface ScriptFont extends LazyFont {
  /** ISO 15924 codes of the scripts it is for, e.g. \`["Beng"]\`. */
  scripts: string[];
}
/**
 * The rest of Typst's bundled faces, registered lazily (${families(extras)}): with \`baseFonts\`, every face
 * native typst embeds, so engines that register both pick the same faces it does.
 */
export declare const extraFonts: LazyFont[];
/** Fonts for scripts the bundled fonts lack, registered lazily: ${families(scripts)}, regular and bold. */
export declare const scriptFonts: ScriptFont[];
`,
);
console.log(
  `fonts.js: ${base.length} base fonts, ${extras.length} extra fonts, ${scripts.length} script fonts (${js.length} bytes)`,
);
