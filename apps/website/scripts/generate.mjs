// Writes the docs pages that come from the packages themselves, before `next dev` / `next build`:
//
//   content/docs/reference/edu/vocabulary.mdx   @typstream/edu's functions, from `eduCatalogue`: the
//       `///` doc comments in packages/edu/typst/, the same source as the prompt kit. Every example
//       is rendered live by <TypstPreview>, so an example that stops compiling shows on the page.
//
// Reads the built package (dist/), which turbo builds first (`^build`).

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { EDU_ROOT, eduCatalogue, eduTemplates } from "@typstream/edu";

const root = fileURLToPath(new URL("..", import.meta.url));

/** The kinds of packages/edu/README.md's vocabulary table, in its order. */
const GROUPS = [
  [
    "Templates",
    "Applied to the whole document with `#show: name.with(…)`.",
    ["worksheet", "quiz", "exam", "lesson-plan", "handout"],
  ],
  [
    "Questions",
    "Numbered through the document; each keeps its points for the totals.",
    ["question", "mcq", "true-false", "matching"],
  ],
  [
    "Answer spaces",
    "Where students write. Each takes an `answer` that only the teacher's copy shows.",
    ["blank", "answer-lines", "answer-space"],
  ],
  ["Answers", 'Hidden unless `sys.inputs.showAnswers` is `"true"`.', ["answer", "answer-key"]],
  [
    "Teaching content",
    "Boxes, lists and tables around the questions.",
    ["callout", "instructions", "learning-objectives", "rubric", "student-info"],
  ],
  [
    "Drawings",
    "Native Typst shapes; inline SVG with an `aria-label` in HTML.",
    ["number-line", "graph-paper", "coordinate-plane"],
  ],
  ["Chemistry", "An mhchem-like subset written as math, so HTML gets MathML.", ["ce"]],
];

/** Escapes text for MDX outside inline code: `{`, `}` and `<` would start expressions and tags. */
const mdx = (text) =>
  text
    .split(/(`[^`]*`)/)
    .map((part, i) => (i % 2 ? part : part.replace(/[{}<]/g, (c) => `\\${c}`)))
    .join("");

const byName = new Map(eduCatalogue.map((doc) => [doc.name, doc]));
const listed = new Set(GROUPS.flatMap(([, , names]) => names));
const missing = eduCatalogue.filter((doc) => !listed.has(doc.name)).map((doc) => doc.name);
// A new edu function goes in a group here, so it can't silently miss the reference.
if (missing.length) throw new Error(`generate.mjs: add ${missing.join(", ")} to GROUPS`);

const out = [
  "---",
  "title: Edu vocabulary",
  `description: Every function and template in @typstream/edu (${EDU_ROOT}), with its signature, parameters and a live example.`,
  "---",
  "",
  "{/* Generated by apps/website/scripts/generate.mjs from @typstream/edu's eduCatalogue. Don't edit: edit the `///` comments in packages/edu/typst/. */}",
  "",
  "This page is generated from the doc comments in `@typstream/edu`'s Typst sources: the same text the",
  "[prompt kit](/docs/guides/prompting) gives the model, so the two can't drift apart. Each example below is",
  "compiled live in your browser; tick **Show answers** to see the teacher's copy.",
  "",
  `Documents get every name below through the plugin's preamble (\`#import "${EDU_ROOT}": *\`), so they`,
  "call `#question(…)` directly. See [@typstream/edu](/docs/reference/edu) for setup.",
  "",
];

for (const [group, intro, names] of GROUPS) {
  out.push(`## ${group}`, "", intro, "");
  for (const name of names) {
    const doc = byName.get(name);
    if (!doc) throw new Error(`generate.mjs: ${name} is not in eduCatalogue`);
    out.push(`### \`${name}\``, "", "```typst", doc.signature, "```", "", mdx(doc.description.trim()), "");
    if (doc.example) {
      // Templates fill a page; give them room.
      const height = group === "Templates" ? 420 : 260;
      out.push(
        `<TypstPreview edu answers height={${height}}>`,
        "",
        "```typst",
        doc.example.trim(),
        "```",
        "",
        "</TypstPreview>",
        "",
      );
    }
  }
}

out.push(
  "## Templates as `template` names",
  "",
  'Apps that ask the model for a body only can apply a template themselves: `<Typstream template="quiz">` (or',
  "`mountTypstream`'s `template` option) looks the name up in the plugins' `templates`. A document that writes its own",
  "`#show: quiz.with(…)` must not get one too: it would apply twice.",
  "",
  "| Name | Title | What it adds |",
  "| --- | --- | --- |",
  ...eduTemplates.map((t) => `| \`${t.name}\` | ${t.title ?? ""} | ${mdx(t.description ?? "")} |`),
  "",
);

const file = `${root}content/docs/reference/edu/vocabulary.mdx`;
const text = `${out.join("\n").replace(/\n{3,}/g, "\n\n")}`;
mkdirSync(dirname(file), { recursive: true });
let previous = "";
try {
  previous = readFileSync(file, "utf8");
} catch {}
// Rewriting an unchanged file would restart `next dev`'s MDX compile for nothing.
if (previous !== text) writeFileSync(file, text);
console.log(`generate.mjs: ${eduCatalogue.length} edu functions → content/docs/reference/edu/vocabulary.mdx`);
